"""Continuity across separate `team.py do` invocations on the same project.

Every `do` call was previously a blank slate: no memory of what was asked for
before, and no visibility into files a previous call already wrote unless the
operator passed `--paths` by hand. That makes "now make it faster" or "add a
save function to that game" not really work -- the planner cannot build on
code it has never been shown, and has no idea a first request even happened.

This keeps a small append-only transcript per project (one JSON file, keyed by
the project's absolute path, same convention as `_plan_path`) and renders it
plus a listing of the project's current files into one text block that gets
folded into the planner's `context`. No model is consulted to produce it --
a plain structured summary of what happened is nearly free, and spending a
model call to compress a handful of one-line turn summaries would cost more
than it saves. Compressing further only becomes worth it once a transcript
is long enough that a fixed --limit tail is not enough context, which has not
been observed yet; the hook to add it later is `history_block`'s one call
site in `team.py`, not a rewrite.

Deliberately not tied to any particular calling agent -- this is a plain JSON
file read and written by the CLI itself, so a human, Claude, GPT, or a script
all see the same continuity by running `team.py do` in the same directory.
Binding it to "whichever model is asking" would make the history depend on
who happened to be driving, which defeats the point of it being memory.
"""
from __future__ import annotations

import ast
import hashlib
import json
import os
import time
from typing import Any, Dict, List, Optional

import swarm

SESSION_DIR = os.path.join(swarm.HERE, ".swarm", "sessions")
# A turn is a few lines of JSON -- a request string and a handful of paths --
# so there is no real storage cost to keeping all of them, and no reason to
# throw away history a later feature (a `history` subcommand, say) might want
# to read further back than the planner currently does. The number that
# actually controls prompt cost is HISTORY_LIMIT below.
MAX_TURNS = None


def project_key(root: str) -> str:
    """Stable identity for a project directory. One definition, used by all.

    `realpath`, not `abspath`, because the two disagree the moment a symlink
    is involved and that disagreement silently splits one project's state in
    two. `project_root()` returns `os.getcwd()`, which the OS has already
    resolved, while anything passing a path in by hand -- `SWARM_ROOT`, a
    test, a shell alias through a symlinked directory -- has not. On macOS
    `/tmp` is a symlink to `/private/tmp`, so the same directory reached those
    two ways produced two different keys and a project that appeared to have
    forgotten everything.

    Public, and `team._plan_path` uses it too, because the failure of having
    two of these is not that either is wrong -- it is that history and the
    saved plan would key differently, so a `--retry` could find its plan while
    the planner found no history for the same directory.
    """
    return hashlib.sha1(
        os.path.realpath(root).encode("utf-8")).hexdigest()[:16]


def _session_path(root: str) -> str:
    return os.path.join(SESSION_DIR, project_key(root) + ".json")


def turns(root: str) -> List[Dict[str, Any]]:
    """Every recorded turn for this project, oldest first, or []."""
    try:
        with open(_session_path(root), encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return []


def _why(spec: str, width: int = 150) -> str:
    """One line of a component's spec: what this file was for.

    The planner already wrote the reason -- that is what a spec is -- so the
    rationale never needs to be generated by anybody. It only needs to stop
    being thrown away, which is what this whole field is. First non-empty
    line, because specs open with the summary sentence and continue into
    detail the history does not need.
    """
    for line in (spec or "").splitlines():
        line = line.strip().lstrip("-*# ").strip()
        if line:
            return line[:width]
    return ""


def record(root: str, request: str, components: List[Any], ok: int,
          total: int, elapsed: float,
          existing: Optional[Any] = None,
          check: Optional[str] = None) -> None:
    """Append one turn. Never raises -- losing history must not fail a run.

    `plan` is the part that makes a follow-up request intelligible. Without
    it a turn reads "you asked X, 3/3 passed, these files changed", which
    says nothing about why the work was split the way it was or which file
    owns which concern -- so "make the bounds check stricter" three turns
    later has nothing to attach itself to and the planner invents a new file.

    Every field of it is already in hand when this is called and was
    previously discarded: `components` carries each spec, floor, dependency
    list, attempt count and error. Recording them costs a few hundred bytes
    and no model call, which is the same argument that kept a model out of
    the rest of this module -- except here the information is not even being
    compressed, merely kept.
    """
    try:
        prior = set(existing or ())
        history = turns(root)
        history.append({
            "when": time.time(),
            "request": request,
            "files": sorted({c.path for c in components}),
            "ok": ok,
            "total": total,
            "seconds": round(elapsed, 1),
            "check": check or "",
            "plan": [{
                "path": getattr(c, "path", ""),
                "why": _why(getattr(c, "spec", "")),
                "floor": getattr(c, "floor", 0),
                "deps": list(getattr(c, "deps", []) or []),
                "ok": bool(getattr(c, "ok", False)),
                "attempts": int(getattr(c, "attempts", 0) or 0),
                # Whether this revised a file or created one. The planner's
                # next decision is usually "edit that, or write something
                # new", and knowing which way it went last time is the most
                # directly useful fact in the turn.
                "edited": os.path.normpath(getattr(c, "path", "")) in prior,
                "error": (getattr(c, "error", "") or "")[:200],
            } for c in components],
        })
        if MAX_TURNS is not None:
            history = history[-MAX_TURNS:]
        os.makedirs(SESSION_DIR, exist_ok=True)
        with open(_session_path(root), "w", encoding="utf-8") as fh:
            json.dump(history, fh, indent=2)
    except OSError:
        pass


def _tools_path(root: str) -> str:
    return os.path.join(SESSION_DIR, project_key(root) + ".tools.json")


def tool_turns(root: str) -> List[Dict[str, Any]]:
    """Every recorded tool call for this project, oldest first, or []."""
    try:
        with open(_tools_path(root), encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return []


def record_tools(root: str, request: str, records: List[Dict[str, Any]]) -> None:
    """Append what `tools.py` proposed and what happened to it.

    Kept in a separate file from the `do` transcript rather than interleaved,
    because the two answer different questions: that one is "what has been
    asked of this project", this one is "what has been done to this machine".
    An executor that takes actions and keeps no record of them is strictly
    worse than one that does, and the record costs a few lines of JSON.

    Declined and invalid calls are recorded too. A refusal is the interesting
    case -- it is the evidence for whether the confirm gate is catching
    anything, which is the question the gate's existence rests on.
    """
    try:
        history = tool_turns(root)
        for record in records:
            history.append({
                "when": time.time(),
                "request": request,
                "tool": record.get("tool", ""),
                "args": record.get("args", {}),
                "status": record.get("status", ""),
                "ran": bool(record.get("ran")),
            })
        os.makedirs(SESSION_DIR, exist_ok=True)
        with open(_tools_path(root), "w", encoding="utf-8") as fh:
            json.dump(history, fh, indent=2)
    except OSError:
        pass


def _attach_path(root: str) -> str:
    return os.path.join(SESSION_DIR, project_key(root) + ".attach.json")


def attachments(root: str) -> List[str]:
    """Reference files currently attached to this project, or [].

    Paths only. `attach.py` re-reads the files on every run, so a design
    document edited between two requests takes effect on the second one
    without being re-attached -- which is the behaviour an operator expects
    from something described as attached to the project.
    """
    try:
        with open(_attach_path(root), encoding="utf-8") as fh:
            found = json.load(fh)
        return [p for p in found if isinstance(p, str)]
    except (OSError, ValueError):
        return []


def set_attachments(root: str, paths: List[str]) -> None:
    """Replace the attachment list, or remove it entirely when empty.

    Replace rather than append, because the flag that writes this states the
    set rather than adding to it. Appending would let a list grow across runs
    without the operator ever naming the whole of it, and every entry is
    carried in every writer's prompt -- an invisible accumulation is exactly
    the cost that should not be possible to incur by accident.
    """
    try:
        if not paths:
            if os.path.exists(_attach_path(root)):
                os.remove(_attach_path(root))
            return
        os.makedirs(SESSION_DIR, exist_ok=True)
        with open(_attach_path(root), "w", encoding="utf-8") as fh:
            json.dump(paths, fh, indent=2)
    except OSError:
        pass


def _age(when: float) -> str:
    seconds = max(0.0, time.time() - when)
    if seconds < 90:
        return "just now"
    if seconds < 3600:
        return "%d min ago" % (seconds / 60)
    if seconds < 86400:
        return "%.0f hr ago" % (seconds / 3600)
    return "%.0f day(s) ago" % (seconds / 86400)


HISTORY_LIMIT = 20  # what the planner actually sees, out of everything stored


def file_reasons(root: str) -> Dict[str, Dict[str, Any]]:
    """For each path, why it last changed -- the most recent turn that touched it.

    Keyed by file rather than windowed by time, which is the whole point.
    Detailing the N most recent turns was the obvious design and it is
    backwards: it spends the budget on whatever happened last, so five
    consecutive tidy-ups of one helper crowd out the turn that explains why
    the bounds checking lives in `vm_engine.py`, and repeat one line five
    times while doing it.

    Per file, the cost is bounded by the number of files instead of the
    number of requests, nothing is ever repeated, and a reason survives for
    as long as the file does. A project can be asked for a hundred things and
    this stays the size of the directory listing it decorates.

    Later turns overwrite earlier ones deliberately: what matters is why the
    file is the way it is *now*, not the sequence that got it there. The
    sequence is still on disk, and `history_block` still renders it.
    """
    reasons: Dict[str, Dict[str, Any]] = {}
    for turn in turns(root):
        for part in turn.get("plan", []):
            path, why = part.get("path"), part.get("why")
            if path and why and part.get("ok"):
                reasons[os.path.normpath(path)] = {
                    "why": why,
                    "request": turn.get("request", ""),
                    "when": turn.get("when", 0),
                }
    return reasons


def history_block(root: str, limit: int = HISTORY_LIMIT) -> str:
    """Recent turns, rendered as text a planner prompt can fold in.

    One line each: what was asked, what changed, whether it worked. The
    reasoning behind each file lives in `existing_files_block` instead,
    attached to the file it explains, because that is where the planner's
    actual decision gets made -- which path to target.

    Deliberately no file contents. Those are covered by
    `existing_files_block` and by the writer's own copy of any file it edits,
    and repeating them per turn would grow without bound.

    A turn that failed keeps its reason here rather than in the per-file map,
    because a file that never got written has nothing to attach a reason to,
    and "this was attempted and did not work" is exactly what a planner needs
    in order not to try it the same way again.
    """
    recent = turns(root)[-limit:]
    if not recent:
        return ""
    lines = ["This project has prior history in this directory. Earlier "
             "requests, oldest first:"]
    for i, turn in enumerate(recent, 1):
        lines.append("  %d. (%s) \"%s\" -> %s (%d/%d ok)" % (
            i, _age(turn.get("when", 0)), turn.get("request", "")[:160],
            ", ".join(turn.get("files", [])) or "no files recorded",
            turn.get("ok", 0), turn.get("total", 0)))
        for part in turn.get("plan", []):
            if not part.get("ok"):
                lines.append("       %s was attempted and FAILED: %s"
                             % (part.get("path", "?"),
                                part.get("error") or "no reason recorded"))
    lines.append("Build on this existing work rather than starting over, "
                 "unless the request below clearly asks for something new "
                 "and unrelated. When a request refines something above, "
                 "target the file that already owns that concern.")
    return "\n".join(lines)


def defines_main(path: str) -> bool:
    """Whether this file is something an operator runs.

    Off the syntax tree rather than by filename, because the entry point is
    not always called main.py, and a file called main.py is not always one.
    """
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            tree = ast.parse(fh.read())
    except (OSError, SyntaxError, ValueError):
        return False
    return any(isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
               and node.name == "main" for node in tree.body)


def existing_files_block(root: str, public_names) -> str:
    """What is already on disk, and the names each file already offers.

    `public_names` (from `team.py`) is passed in rather than imported, because
    `team` imports this module -- importing back would be circular -- and the
    caller already has the function loaded regardless.
    """
    try:
        names_on_disk = sorted(os.listdir(root))
    except OSError:
        return ""
    # Non-Python files are listed too. They cannot offer importable names,
    # but they are real dependencies -- a page a script opens at run time --
    # and a planner that cannot see survey.html has no way to depend on it,
    # so it plans a second copy. Restricted to the types this pool can
    # write, or a listing fills up with .DS_Store and binaries.
    import intent
    files = [f for f in names_on_disk
             if os.path.isfile(os.path.join(root, f))
             and not f.startswith(".")
             and os.path.splitext(f)[1].lower() in intent.WRITABLE
             # A straggler from a losing race/hedge candidate (see
             # `team._race_scratch_path`) that finished writing after its
             # own call already lost is real content on disk, but it is
             # not something the operator or a planner ever asked for.
             and not intent.is_race_scratch_name(f)]
    if not files:
        return ""
    reasons = file_reasons(root)
    lines = [
        "This directory already contains these files. There are two "
        "different things the request below can be, and they want opposite "
        "decisions:",
        "",
        "  - It revises behaviour that is already here: make it stricter or "
        "faster, fix a bug, change what it prints or returns. Name the SAME "
        "path, so that file is edited in place instead of duplicated under a "
        "new name.",
        "  - It asks for something new: another script, another page, a "
        "second tool that uses what is here. Give it a NEW path and list the "
        "existing files it needs as dependencies. Do not reuse main.py or "
        "any other existing path for it.",
        "",
        "Reusing a path is not free. A component replaces its whole file, so "
        "naming an existing path for new work deletes whatever that file did "
        "-- a working script the operator still runs becomes a different "
        "script. When in doubt between the two, a new path costs a filename "
        "and reusing one costs the file.",
        "",
        "The files:"]
    for name in files:
        path = os.path.join(root, name)
        if name.endswith(".py"):
            names = public_names(path)
            # `public_names` excludes `main` on purpose: it is not something
            # an importer asks for. That left the entry point as a bare
            # filename with nothing beside it -- the one file whose role
            # most needs saying, and the one a planner should think hardest
            # about before reusing the path.
            note = " -- defines " + ", ".join(names) if names else ""
            if defines_main(path):
                note += ("; runnable entry point" if note
                         else " -- runnable entry point")
        else:
            note = " -- not a module; a script can open it at run time"
        lines.append("  %s%s" % (name, note))
        # What the file is for, next to what it offers. The symbol list says
        # `vm_engine.py` defines `VM` and `run`; only this says the bounds
        # checking is in there because an earlier request asked that a bad
        # jump target not crash the program. A follow-up of "make that
        # stricter" is answerable from the second and not from the first.
        reason = reasons.get(os.path.normpath(name))
        if reason:
            lines.append("      last changed for \"%s\": %s"
                         % (reason["request"][:80], reason["why"]))
    return "\n".join(lines)


def context_for(root: str, public_names, limit: int = HISTORY_LIMIT) -> str:
    """The full continuity block: recent history plus what already exists."""
    parts = [b for b in (history_block(root, limit),
                        existing_files_block(root, public_names)) if b]
    return "\n\n".join(parts)


def question_context(root: str, public_names, request: str,
                     paths: Optional[List[str]], cfg: Any,
                     limit: int = HISTORY_LIMIT) -> str:
    """Ground a plain question in this project, the same way `code` already
    is, since a question had nothing here before.

    `code` gets `context_for` (history plus file names and reasons) and a
    writer editing an existing file additionally gets that file's own real
    content. A question -- "why does main.py look like that, please give
    guidance on how to use it" -- got neither: the bare request text
    carries no file names and no code, so a model asked about "the file"
    had to guess what it even was, and the answer was ungrounded whether
    or not the guess happened to be right. There was no missing command
    here; `ask`'s existing fallback simply never carried the project with
    it the way every other path in this pipeline does.

    Which files to show: whichever the caller already resolved (from
    triage or an explicit `--paths`) if any named a real file, else
    whichever the request text itself names by extension, else every
    writable file at the project root -- because "why does the file look
    like that" with no path at all still means something specific once
    there is only a handful of candidates on disk to mean.

    Read-only, so unlike `--attach` this never refuses outright on size:
    the worst case of trimming a file out under budget is a slightly less
    complete answer, never a broken run. Largest goes first when trimming,
    the same rule `openapi.slice_for` uses when a set has to shrink -- the
    biggest file is the one least likely to be what a short question was
    actually about, and the cheapest to give up first.
    """
    import re
    import attach
    import intent
    import swarm as _swarm

    ctx = context_for(root, public_names, limit)

    mentioned = [p for p in (paths or [])
                if os.path.isfile(os.path.join(root, p))]
    if not mentioned:
        candidates = re.findall(
            r"[\w./-]+\.(?:%s)" % "|".join(
                sorted(e.lstrip(".") for e in intent.WRITABLE)), request)
        mentioned = [p for p in candidates
                    if os.path.isfile(os.path.join(root, p))]
    if not mentioned:
        try:
            mentioned = [f for f in sorted(os.listdir(root))
                        if os.path.isfile(os.path.join(root, f))
                        and not f.startswith(".")
                        and os.path.splitext(f)[1].lower() in intent.WRITABLE
                        and not intent.is_race_scratch_name(f)]
        except OSError:
            mentioned = []
    if not mentioned:
        return ctx

    content, _problems = attach.read(root, mentioned)
    if not content:
        return ctx

    def rendered() -> str:
        parts = []
        for p in sorted(content):
            parts.append("\n--- %s ---\n```%s\n%s\n```\n"
                         % (p, attach.fence(p), content[p].rstrip("\n")))
        return "".join(parts)

    order = sorted(content, key=lambda p: len(content[p]), reverse=True)
    while order and _swarm.est_tokens(ctx + rendered()) > attach.budget(cfg):
        content.pop(order.pop(0))
    if not content:
        return ctx
    return ctx + ("\nThe actual, current content of this project's own "
                  "files, so the answer is grounded in what is really "
                  "here rather than a guess:" + rendered())
