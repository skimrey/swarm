"""team.run_with_gateway_retry / looks_like_transient_gateway_error.

Measured live: `07_update_project`'s real PATCH carried exactly the
right payload -- the same shape that succeeded in every other run -- and
CloudFront answered with a literal "504 Server Error: Gateway Timeout"
and its own error page HTML, never having reached the real origin in
time. Feeding that into the model repair loop would spend a repair
attempt rewriting code that was never wrong; the actual fix an operator
would do by hand is rerun the identical script a moment later. This is
purely mechanical: a regex match on the real captured output of
`--run`'s own `run_and_capture`, with no model and no code change.

Run directly: `python3 scratch_gateway_retry.py`.
"""
import team


LIVE_504_OUTPUT = (
    "Attempting to update Project 447a3f47-... to use Applet Version "
    "c78d6a96-...\n"
    "HTTP Error updating project: 504 Server Error: Gateway Timeout for "
    "url: https://dztfdhkmj6wqi.cloudfront.net/api/projects/447a3f47-...\n"
    "PATCH https://dztfdhkmj6wqi.cloudfront.net/api/projects/447a3f47-...\n"
    "response body: <!DOCTYPE HTML PUBLIC \"-//W3C//DTD HTML 4.01 "
    "Transitional//EN\">\n<HTML><HEAD>...<H1>504 Gateway Timeout "
    "ERROR</H1>...Generated by cloudfront\n"
)


def test_recognizes_502_503_504():
    for code in (502, 503, 504):
        text = "%d Server Error: something for url: http://x" % code
        assert team.looks_like_transient_gateway_error(text), text
    print("  502, 503, and 504 are all recognized")


def test_does_not_flag_a_plain_500_or_a_4xx():
    # A bare 500 is usually the application itself raising on the
    # request it was actually given -- not safe to wave off as "just
    # retry the same bytes" the way a gateway timeout is.
    assert not team.looks_like_transient_gateway_error(
        "500 Server Error: Internal Server Error for url: http://x")
    assert not team.looks_like_transient_gateway_error(
        "401 Client Error: Unauthorized for url: http://x")
    assert not team.looks_like_transient_gateway_error(
        "422 Client Error: Unprocessable Entity for url: http://x")
    print("  a plain 500 and ordinary 4xx client errors are left alone")


def test_the_live_504_is_recognized_verbatim():
    assert team.looks_like_transient_gateway_error(LIVE_504_OUTPUT)
    print("  the exact live 504 CloudFront output is recognized")


def test_retries_and_succeeds_on_the_second_attempt():
    calls = []
    sleeps = []

    def fake_run_and_capture(root, target_file):
        calls.append((root, target_file))
        if len(calls) == 1:
            return 1, LIVE_504_OUTPUT
        return 0, "Successfully updated Project ...\n"

    real = team.run_and_capture
    team.run_and_capture = fake_run_and_capture
    try:
        code, output, retries = team.run_with_gateway_retry(
            "/tmp/proj", "main.py", sleep=lambda s: sleeps.append(s))
    finally:
        team.run_and_capture = real

    assert code == 0, (code, output)
    assert retries == 1, retries
    assert len(calls) == 2, "did not actually rerun the identical script"
    assert calls[0] == calls[1] == ("/tmp/proj", "main.py"), calls
    assert len(sleeps) == 1, "should back off before the one retry"
    print("  a 504 on attempt 1 is retried unchanged and succeeds on "
          "attempt 2, with exactly one backoff")


def test_gives_up_after_max_retries_if_still_gateway_errors():
    calls = []

    def always_504(root, target_file):
        calls.append(1)
        return 1, LIVE_504_OUTPUT

    real = team.run_and_capture
    team.run_and_capture = always_504
    try:
        code, output, retries = team.run_with_gateway_retry(
            "/tmp/proj", "main.py", max_retries=3, sleep=lambda s: None)
    finally:
        team.run_and_capture = real

    assert code == 1, code
    assert retries == 3, retries
    assert len(calls) == 4, (
        "expected the original attempt plus 3 retries, got %d" % len(calls))
    print("  a persistent gateway error stops after max_retries rather "
          "than looping forever")


def test_a_non_gateway_failure_is_not_retried_at_all():
    calls = []

    def fails_with_a_real_bug(root, target_file):
        calls.append(1)
        return 1, "KeyError: 'project_id'"

    real = team.run_and_capture
    team.run_and_capture = fails_with_a_real_bug
    try:
        code, output, retries = team.run_with_gateway_retry(
            "/tmp/proj", "main.py", sleep=lambda s: None)
    finally:
        team.run_and_capture = real

    assert code == 1
    assert retries == 0, "a real code defect must not be retried unchanged"
    assert len(calls) == 1, (
        "a non-gateway failure was rerun anyway -- wasted a real attempt")
    print("  a genuine code failure (no 502/503/504) is not retried at all")


def test_a_clean_success_needs_no_retry():
    calls = []

    def succeeds(root, target_file):
        calls.append(1)
        return 0, "Successfully updated Project ...\n"

    real = team.run_and_capture
    team.run_and_capture = succeeds
    try:
        code, output, retries = team.run_with_gateway_retry(
            "/tmp/proj", "main.py", sleep=lambda s: None)
    finally:
        team.run_and_capture = real

    assert code == 0 and retries == 0 and len(calls) == 1
    print("  a clean first attempt is not retried")


def test_a_timeout_none_code_is_not_retried():
    # run_and_capture returns (None, "") on a timeout -- not a status
    # code at all, so there is nothing to regex-match and no reason to
    # spend a retry on it.
    def times_out(root, target_file):
        return None, ""

    real = team.run_and_capture
    team.run_and_capture = times_out
    try:
        code, output, retries = team.run_with_gateway_retry(
            "/tmp/proj", "main.py", sleep=lambda s: None)
    finally:
        team.run_and_capture = real

    assert code is None and retries == 0
    print("  a timeout (code=None) is left alone, not retried")


def main():
    test_recognizes_502_503_504()
    test_does_not_flag_a_plain_500_or_a_4xx()
    test_the_live_504_is_recognized_verbatim()
    test_retries_and_succeeds_on_the_second_attempt()
    test_gives_up_after_max_retries_if_still_gateway_errors()
    test_a_non_gateway_failure_is_not_retried_at_all()
    test_a_clean_success_needs_no_retry()
    test_a_timeout_none_code_is_not_retried()
    print("OK")


if __name__ == "__main__":
    main()
